// error-characteristics: shows one sensor error at a time, without a physics engine.
//
// A rigid body moves along a motion written as a formula. The host helpers of this repository
// (host/sensor_host.hpp) turn that motion and the mounting pose into the sensor truth, and the truth goes through
// an implementation's adapter, chosen by name through the common interface. Physics steps write the truth and the
// measurement to CSV, so the plots can lay one error over the truth.
//
//   error-characteristics --implementation hakoniwa --sensor imu|mag|baro|gps --config <file> --motion <name>
//                         --out <file.csv> [--duration S] [--step-us 1000] [--seed N]
//                         [--mount x,y,z,roll,pitch,yaw] [--rate R] [--t0 S] [--every N]
//
// Motions (world NWU, body FLU; the body is level unless it turns):
//   rest     at rest
//   turn     turning about z at --rate rad/s (default pi)
//   step     from --t0 (default 1 s): turning about x at --rate rad/s and accelerating up at 1 m/s^2
//            (the attitude is left level, so the truth is easy to read)
//   ramp     the turn rate about x grows by --rate rad/s per second
//   yawstep  the heading jumps by --rate rad (default pi/2) at --t0
//   hstep    the height jumps by --rate m (default 10) at --t0
//   climb    from --t0, climbing at --rate m/s (default 1)
//   move     from --t0, moving north at --rate m/s (default 5)
//
// The world (field, location, weather) is fixed and illustrative: Tokyo, a 46000 nT field with declination -7.5 deg
// and inclination 49.5 deg, the standard atmosphere at sea level.

