// error-characteristics: shows one sensor error at a time, without a physics engine.
//
// A rigid body moves along a motion written as a formula (at rest, turning, a step, a ramp). The host helpers
// of this repository (host/sensor_host.hpp) turn that motion and the mounting pose into the sensor truth, and
// the truth goes through an implementation's adapter, chosen by name through the common interface. Every
// physics step writes the truth and the measurement to CSV, so the plots can lay one error over the truth.
//
//   error-characteristics --implementation hakoniwa --sensor imu --config <file> --motion <name>
//                         --out <file.csv> [--duration S] [--step-us 1000] [--seed N]
//                         [--mount x,y,z,roll,pitch,yaw] [--rate R] [--every N]
//
// Motions (angular rate and acceleration in body axes; the body is level unless it turns):
//   rest   at rest, level
//   turn   turning about z at --rate rad/s (default 3.14)
//   step   at rest, then from t = --t0 (default 1 s) turning about x at --rate rad/s and accelerating up at 1 m/s^2
//   ramp   the turn rate about x grows linearly by --rate rad/s per second (resolution, then saturation)

#include "hakoniwa/sensor_adapter/host/sensor_host.hpp"
#include "hakoniwa/sensor_adapter/sensor_adapter_implementation.hpp"

#include <algorithm>
#include <cmath>
#include <cstdint>
#include <cstdlib>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

namespace sa = hakoniwa::sensor_adapter;
namespace host = hakoniwa::sensor_adapter::host;

// Generated by CMake from the linked implementation names.
const sa::SensorAdapterImplementation* error_characteristics_find_implementation(const std::string& name);

namespace {

struct Options {
    std::string implementation {"hakoniwa"};
    std::string sensor {"imu"};
    std::string config;
    std::string motion {"rest"};
    std::string out;
    double duration_s {10.0};
    std::uint64_t step_us {1000};
    std::uint64_t seed {1};
    std::vector<double> mount {0, 0, 0, 0, 0, 0};
    double rate {std::nan("")};
    std::uint64_t every {1};  ///< write every N-th step
    double t0 {1.0};          ///< when the step motion starts [s]
};

[[noreturn]] void usage(const std::string& message)
{
    if (!message.empty()) {
        std::cerr << "error-characteristics: " << message << "\n";
    }
    std::cerr << "usage: error-characteristics --implementation <name> --sensor imu --config <file>\n"
                 "         --motion rest|turn|step|ramp --out <file.csv> [--duration S] [--step-us 1000]\n"
                 "         [--seed N] [--mount x,y,z,roll,pitch,yaw] [--rate R] [--every N]\n";
    std::exit(2);
}

std::vector<double> numbers(const std::string& text)
{
    std::vector<double> values;
    std::stringstream stream(text);
    std::string item;
    while (std::getline(stream, item, ',')) {
        values.push_back(std::stod(item));
    }
    return values;
}

Options parse(int argc, char** argv)
{
    Options options;
    for (int index = 1; index < argc; ++index) {
        const std::string key = argv[index];
        auto value = [&]() -> std::string {
            if (index + 1 >= argc) usage(key + " needs a value");
            return argv[++index];
        };
        if (key == "--implementation") options.implementation = value();
        else if (key == "--sensor") options.sensor = value();
        else if (key == "--config") options.config = value();
        else if (key == "--motion") options.motion = value();
        else if (key == "--out") options.out = value();
        else if (key == "--duration") options.duration_s = std::stod(value());
        else if (key == "--step-us") options.step_us = std::stoull(value());
        else if (key == "--seed") options.seed = std::stoull(value());
        else if (key == "--mount") options.mount = numbers(value());
        else if (key == "--rate") options.rate = std::stod(value());
        else if (key == "--t0") options.t0 = std::stod(value());
        else if (key == "--every") options.every = std::max<std::uint64_t>(1, std::stoull(value()));
        else usage("unknown option " + key);
    }
    if (options.config.empty() || options.out.empty()) usage("--config and --out are required");
    if (options.mount.size() != 6) usage("--mount needs x,y,z,roll,pitch,yaw");
    if (options.sensor != "imu") usage("only --sensor imu so far");
    return options;
}

// The rigid body's motion at time t (NWU world, FLU body).
host::RigidBodyMotion motion_at(const Options& options, double t)
{
    host::RigidBodyMotion m;
    const std::string& kind = options.motion;
    if (kind == "rest") {
        return m;
    }
    if (kind == "turn") {
        const double rate = std::isnan(options.rate) ? 3.14159265358979 : options.rate;
        const double yaw = rate * t;
        // world -> body: rotation about z by -yaw
        m.orientation_world_to_body = {std::cos(yaw / 2.0), 0.0, 0.0, -std::sin(yaw / 2.0)};
        m.angular_velocity_body = {0.0, 0.0, rate};
        return m;
    }
    if (kind == "step") {
        const double rate = std::isnan(options.rate) ? 1.0 : options.rate;
        if (t >= options.t0 - 1e-12) {
            m.angular_velocity_body = {rate, 0.0, 0.0};
            m.linear_acceleration_nwu = {0.0, 0.0, 1.0};
        }
        return m;  // the attitude change of the step is left out: the truth stays easy to read
    }
    if (kind == "ramp") {
        const double rate = std::isnan(options.rate) ? 1.0 : options.rate;
        m.angular_velocity_body = {rate * t, 0.0, 0.0};
        m.angular_acceleration_body = {rate, 0.0, 0.0};
        return m;
    }
    usage("unknown motion " + kind);
}

std::string num(double value)
{
    std::ostringstream text;
    text << std::setprecision(10) << value;
    return text.str();
}

}  // namespace

int main(int argc, char** argv)
{
    const Options options = parse(argc, argv);
    const sa::SensorAdapterImplementation* implementation =
        error_characteristics_find_implementation(options.implementation);
    if (implementation == nullptr || implementation->create_imu == nullptr) {
        std::cerr << "error-characteristics: implementation " << options.implementation
                  << " is not linked or has no IMU\n";
        return 1;
    }
    sa::ImuAdapterSetup setup;
    setup.config_path = options.config;
    setup.vehicle_name = "bench";
    setup.physics_step_ns = options.step_us * 1000;
    setup.has_random_seed = true;
    setup.random_seed = options.seed;
    std::string error;
    auto imu = implementation->create_imu(setup, error);
    if (!imu) {
        std::cerr << "error-characteristics: " << error << "\n";
        return 1;
    }

    const host::MountPose mount = host::mount_from_rpy_deg(
        {options.mount[0], options.mount[1], options.mount[2]}, options.mount[3], options.mount[4], options.mount[5]);
    const host::World world;
    std::ofstream out(options.out);
    out << "time,true_gx,true_gy,true_gz,true_ax,true_ay,true_az,"
           "gyro_updated,gx,gy,gz,gyro_flags,accel_updated,ax,ay,az,accel_flags\n";
    const auto steps = static_cast<std::uint64_t>(std::llround(options.duration_s * 1e6 / options.step_us));
    for (std::uint64_t k = 0; k < steps; ++k) {
        const std::uint64_t time_ns = k * setup.physics_step_ns;
        const double t = static_cast<double>(time_ns) * 1e-9;
        const sa::ImuTruth truth = host::imu_truth(time_ns, motion_at(options, t), mount, world);
        sa::ImuSample sample;
        if (!imu->step(truth, sample, error)) {
            std::cerr << "error-characteristics: step " << k << ": " << error << "\n";
            return 1;
        }
        if (k % options.every != 0) {
            continue;
        }
        const auto& g = sample.gyro;
        const auto& a = sample.accel;
        out << num(t) << ',' << num(truth.angular_velocity.x) << ',' << num(truth.angular_velocity.y) << ','
            << num(truth.angular_velocity.z) << ',' << num(truth.specific_force.x) << ','
            << num(truth.specific_force.y) << ',' << num(truth.specific_force.z) << ',' << (g.updated ? 1 : 0)
            << ',' << num(g.value.x) << ',' << num(g.value.y) << ',' << num(g.value.z) << ',' << g.flags << ','
            << (a.updated ? 1 : 0) << ',' << num(a.value.x) << ',' << num(a.value.y) << ',' << num(a.value.z)
            << ',' << a.flags << '\n';
    }
    std::cerr << "error-characteristics: " << steps << " steps of " << options.step_us << " us -> " << options.out
              << "\n";
    return 0;
}
